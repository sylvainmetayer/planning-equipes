// The documentation, written for the site: the Markdown of src/docs/ (three parts,
// docs-parties.json) plus the generated licence inventory, which keeps its place in
// ../docs/ because a script writes it. Read at build time and published under /docs.
// A link to the decisions, the code or any file outside the site becomes a GitHub
// link (written `repo:<path from the repository root>` in the sources); a link to a
// page that does not exist fails the build, an anchor that does not resolve is a
// warning.
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import MarkdownIt from 'markdown-it';
import site from './_data/site.json' with { type: 'json' };
import home from './_data/pages/docs.json' with { type: 'json' };
import { parse as yaml } from 'yaml';
import { typo } from './text.js';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
// DOCS_DIR: read the pages from elsewhere (a snapshot, while they are being rewritten)
const DIR = process.env.DOCS_DIR ?? `${ROOT}site/src/docs/`;
// Generated by a script of the application, so it stays where the script writes it
const EXTERNAL = { 'installer/licences-tierces': 'docs/licences-tierces.md' };
const NAMES = Object.fromEntries(Object.entries(EXTERNAL).map(([n, f]) => [f, n]));
// The order of the parts; the pages of each, and what it says of itself, are the front matter of its index.md
const PART_IDS = ['regles', 'installer', 'comprendre'];
// The player colour of each part, which marks its pages the way a chapter is marked on the site
const PLAYERS = { regles: 2, installer: 1, comprendre: 3 };
const GITHUB = `${site.repo}/blob/main/`;
const warnings = [];
const warn = (message) => warnings.push(message);

// GitHub's own anchors, so that the links written for GitHub keep working
const slugify = (text) => text.toLowerCase().replace(/[^\p{L}\p{N}\p{M} _-]/gu, '').trim().replaceAll(' ', '-');

// A malformed escape in a link is the source's to fix, not a reason to fail the build
const decode = (text) => {
  try {
    return decodeURIComponent(text);
  } catch {
    return text;
  }
};

// 'index' is the home, 'regles/index' the home of a part
const urlOfDoc = (name) => (name === 'index' ? '/docs/' : `/docs/${name.replace(/\/index$/, '')}/`);
const sourcePath = (name) => EXTERNAL[name] ?? `site/src/docs/${name}.md`;

function target(href, published, fromName) {
  if (href.startsWith('#')) return { href: `#${decode(href.slice(1))}` };
  // Absolute links (a site address, an image under /images, a diagram) are left as they are
  if (/^(https?:|mailto:|tel:|\/)/i.test(href)) return { href };
  const [path, rawHash] = href.split('#');
  // The anchors are written as the headings are, accents included: what GitHub's slugs and our ids are
  const hash = rawHash === undefined ? undefined : decode(rawHash);
  const anchor = hash ? `#${hash}` : '';
  // `repo:` is a path from the repository root; any other relative link starts from the source file
  const repoPath = path.startsWith('repo:') ? path.slice(5) : posix.normalize(posix.join(posix.dirname(sourcePath(fromName)), path));
  const doc = NAMES[repoPath] ?? repoPath.match(/^site\/src\/docs\/(.+)\.md$/)?.[1];
  if (doc) {
    if (!published.has(doc)) {
      const message = `${fromName}.md : le lien ${href} ne mène à aucune page de la documentation`;
      throw new Error(message);
    }
    return { href: urlOfDoc(doc) + anchor, doc, hash };
  }
  if (/^docs\/diagrammes\/[^/]+\.svg$/.test(repoPath)) return { href: `/${repoPath}` };
  const kind = repoPath.endsWith('/') || !posix.extname(repoPath) ? 'tree' : 'blob';
  return { href: `${site.repo}/${kind}/main/${repoPath.replace(/\/$/, '')}${anchor}` };
}

// The text of an inline token, line breaks read as spaces
const plainOf = (c) => {
  if (c.type === 'softbreak' || c.type === 'hardbreak') return ' ';
  return c.type === 'text' || c.type === 'code_inline' ? c.content : '';
};
const plain = (inline) => inline.children.map(plainOf).join('');

function renderer(published, state) {
  const md = new MarkdownIt({ html: true, linkify: false, typographer: false });
  const { escapeHtml } = md.utils;
  // Only <sub> and <sup> pass: any other tag in the text is shown as written
  md.renderer.rules.html_inline = (tokens, i) => (/^<\/?(sub|sup)>$/.test(tokens[i].content) ? tokens[i].content : escapeHtml(tokens[i].content));
  md.renderer.rules.html_block = (tokens, i) => `<p>${escapeHtml(tokens[i].content)}</p>\n`;
  // A wide table or block of code scrolls on its own, reachable by keyboard
  md.renderer.rules.table_open = () => '<div class="scroll" role="group" aria-label="Tableau" tabindex="0"><table>\n';
  md.renderer.rules.table_close = () => '</table></div>\n';
  md.renderer.rules.fence = (tokens, i) => {
    const t = tokens[i];
    const lang = t.info.trim().split(/\s+/)[0];
    const cls = lang ? ` class="language-${escapeHtml(lang)}"` : '';
    return `<pre class="scroll" role="group" aria-label="Code" tabindex="0"><code${cls}>${escapeHtml(t.content)}</code></pre>\n`;
  };
  // A capture is a figure with its caption under it, and opens in the site's dialog (/assets/popin.js); without script the link opens the image
  const shot = (inline) => {
    const [c] = inline.children;
    return inline.children.length === 1 && c.type === 'image' && c.attrGet('src').startsWith('/images/') ? c : null;
  };
  // A figure cannot sit in a paragraph: a paragraph holding a capture alone renders as the figure
  const paragraph = (tag) => (tokens, i, o, e, self) => (shot(tokens[tag === 'p' ? i + 1 : i - 1]) ? '' : self.renderToken(tokens, i, o));
  md.renderer.rules.paragraph_open = paragraph('p');
  md.renderer.rules.paragraph_close = paragraph('/p');
  md.renderer.rules.image = (tokens, i) => {
    const t = tokens[i];
    const src = t.attrGet('src');
    const alt = escapeHtml(plain(t));
    const size = imageSize(src);
    const dims = size ? ` width="${size[0]}" height="${size[1]}"` : '';
    const img = `<img src="${escapeHtml(src)}" alt="${alt}"${dims} loading="lazy" decoding="async">`;
    if (!src.startsWith('/images/')) return img;
    const caption = escapeHtml(t.attrGet('title') ?? t.content);
    return `<figure class="capture"><a class="shot" href="${escapeHtml(src)}" data-popin="docs" data-caption="${caption}">${img}</a><figcaption>${caption}</figcaption></figure>\n`;
  };
  md.renderer.rules.code_block = (tokens, i) => `<pre class="scroll" role="group" aria-label="Code" tabindex="0"><code>${escapeHtml(tokens[i].content)}</code></pre>\n`;
  md.core.ruler.push('docs', (s) => {
    const used = new Map();
    let first = true;
    // A heading gets its id and its place in the contents; the first h1 is the page's title and renders as nothing
    const heading = (i) => {
      const t = s.tokens[i];
      const inline = s.tokens[i + 1];
      const text = plain(inline);
      if (t.tag === 'h1' && first) {
        first = false;
        state.h1 = text;
        t.hidden = true; // the page header carries it
        inline.hidden = true;
        s.tokens[i + 2].hidden = true;
        return;
      }
      let id = slugify(text);
      const n = used.get(id) ?? 0;
      used.set(id, n + 1);
      if (n) id += `-${n}`;
      t.attrSet('id', id);
      state.ids.add(id);
      if (t.tag === 'h2' || t.tag === 'h3') state.toc.push({ level: Number(t.tag[1]), id, text });
    };
    const rewrite = (c) => {
      // The site's typography (curly apostrophes, no-break spaces before ? ! : ;), as in its own pages
      if (c.type === 'text') c.content = typo(c.content, 'fr');
      // A text made of an arrow alone (a cell reading "→ `{…}`") is no text to the contrast check: the arrow is decoration
      if (c.type === 'text' && /^\s*→\s*$/.test(c.content)) {
        c.type = 'html_inline';
        c.content = ' <span aria-hidden="true">→</span> ';
      }
      let key = null;
      if (c.type === 'link_open') key = 'href';
      else if (c.type === 'image') key = 'src';
      if (!key) return;
      const r = target(c.attrGet(key), published, state.name);
      c.attrSet(key, r.href);
      if (r.doc || r.href.startsWith('#')) state.links.push({ href: r.href, doc: r.doc, hash: r.hash ?? (r.href.startsWith('#') ? r.href.slice(1) : '') });
      if (c.type === 'image' && !c.content) warn(`${state.name}.md : image sans texte alternatif (${r.href})`);
    };
    for (let i = 0; i < s.tokens.length; i++) {
      const t = s.tokens[i];
      if (t.type === 'heading_open') heading(i);
      if (t.type === 'paragraph_open' && !state.lead) state.lead = plain(s.tokens[i + 1]);
      // A cell's alignment is a class, not an inline style (the CSP forbids it)
      if (t.type === 'th_open' || t.type === 'td_open') {
        const align = t.attrGet('style')?.match(/text-align:(\w+)/)?.[1];
        t.attrs = align ? [['class', `align-${align}`]] : null;
      }
      t.children?.forEach(rewrite);
    }
  });
  // Hidden tokens render as nothing
  const base = md.renderer.render.bind(md.renderer);
  md.renderer.render = (tokens, ...rest) => base(tokens.filter((t) => !t.hidden), ...rest);
  return md;
}

// Width and height of a WebP capture, read from its header, so that the page does not jump as it loads
function imageSize(src) {
  if (!src.startsWith('/images/')) return null;
  try {
    const b = readFileSync(`${ROOT}site/src${src}`);
    const kind = b.toString('ascii', 12, 16);
    if (kind === 'VP8X') return [1 + b.readUIntLE(24, 3), 1 + b.readUIntLE(27, 3)];
    if (kind === 'VP8L') return [1 + (b.readUInt16LE(21) & 0x3fff), 1 + ((b.readUInt32LE(21) >> 14) & 0x3fff)];
    if (kind === 'VP8 ') return [b.readUInt16LE(26) & 0x3fff, b.readUInt16LE(28) & 0x3fff];
  } catch {
    warn(`image introuvable : ${src}`);
  }
  return null;
}

const cut = (text, max) => {
  const flat = text.replace(/\s+/g, ' ').trim();
  if (flat.length <= max) return flat;
  const space = flat.lastIndexOf(' ', max - 1);
  return `${flat.slice(0, space > 0 ? space : max - 1)}…`;
};

function readDoc(name, published) {
  const raw = readFileSync(EXTERNAL[name] ? `${ROOT}${EXTERNAL[name]}` : `${DIR}${name}.md`, 'utf8');
  const front = raw.match(/^---\n([\s\S]*?)\n---\n/);
  const meta = front ? yaml(front[1]) : {};
  const source = front ? raw.slice(front[0].length) : raw;
  const state = { name, ids: new Set(), toc: [], links: [], h1: '', lead: '' };
  const body = renderer(published, state).render(source, {});
  if (!state.h1) warn(`${name}.md : pas de titre de niveau 1`);
  const h1 = state.h1 || name;
  const isHome = name === 'index';
  return {
    name,
    url: urlOfDoc(name),
    doc: true,
    lang: 'fr',
    key: 'docs',
    h1,
    // The home of /docs takes its title and description from the CMS (docs.json)
    title: isHome ? typo(home.titre, 'fr') : `${cut(typo(h1, 'fr'), 34)} | Documentation | ${site.name}`,
    kind: isHome ? 'home' : name.endsWith('/index') ? 'part' : 'page',
    description: isHome ? typo(home.description, 'fr') : cut(state.lead || h1, 155),
    body,
    meta,
    edit: EXTERNAL[name] ? undefined : `${site.repo}/edit/main/${sourcePath(name)}`,
    toc: state.toc,
    source,
    state,
  };
}

let cache;
let cachedParts;
export function loadParts() {
  loadDocs();
  return cachedParts;
}
export function loadDocs() {
  if (cache) return cache;
  const walk = (dir) => readdirSync(`${DIR}${dir}`).flatMap((f) => (statSync(`${DIR}${dir}${f}`).isDirectory() ? walk(`${dir}${f}/`) : f.endsWith('.md') ? [`${dir}${f.slice(0, -3)}`] : []));
  const names = [...walk(''), ...Object.keys(EXTERNAL)];
  const published = new Set(names);
  const docs = names.map((name) => readDoc(name, published));
  const byName = Object.fromEntries(docs.map((d) => [d.name, d]));
  for (const d of docs) {
    for (const { doc, hash, href } of d.state.links) {
      if (!hash) continue;
      const ids = (doc ? byName[doc] : d).state.ids;
      if (ids.has(hash)) continue;
      throw new Error(`${d.name}.md : ancre #${hash} introuvable dans ${doc ?? d.name}.md`);
    }
  }
  const parts = PART_IDS.map((id) => {
    const home = byName[`${id}/index`];
    if (!home) throw new Error(`site/src/docs/${id}/index.md manque`);
    return { id, player: PLAYERS[id], titre: home.meta.titre, pour: home.meta.pour, docs: (home.meta.docs ?? []).map((n) => `${id}/${n}`) };
  });
  cachedParts = parts;
  // Every page belongs to exactly one part (its folder), is listed once in the front matter of its part's index.md
  for (const d of docs) {
    d.part = d.name === 'index' ? undefined : parts.find((p) => p.docs.includes(d.name) || d.name === `${p.id}/index`)?.id;
    if (d.name !== 'index' && !d.part) throw new Error(`${sourcePath(d.name)} : absente du front matter (docs:) de l'index de sa partie`);
  }
  for (const p of parts) {
    for (const n of p.docs) if (!byName[n]) throw new Error(`${p.id}/index.md : « ${n} » n'existe pas`);
    if (new Set(p.docs).size !== p.docs.length) throw new Error(`${p.id}/index.md : une page est listée deux fois`);
  }
  // Reading order inside a part: the previous and the next guide
  for (const p of parts) {
    const order = [`${p.id}/index`, ...p.docs];
    order.forEach((n, i) => {
      byName[n].prev = order[i - 1];
      byName[n].next = order[i + 1];
    });
  }
  for (const d of docs) delete d.state;
  docs.sort((a, b) => Number(b.name === 'index') - Number(a.name === 'index') || a.name.localeCompare(b.name, 'fr'));
  for (const w of warnings) console.warn(`[docs] ${w}`);
  cache = docs;
  return cache;
}
